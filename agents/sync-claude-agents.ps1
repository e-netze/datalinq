# Generates the Claude Code agents (agents/claude/*.md) from the Copilot agents (agents/copilot/*.agent.md).
# The Copilot files are the single source of truth for the agent bodies; only the frontmatter differs.
# Usage: pwsh ./agents/sync-claude-agents.ps1   (run after every change to agents/copilot/*.agent.md)

$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$src = Join-Path $root 'copilot'
$dst = Join-Path $root 'claude'

# Copilot tool alias -> Claude Code tool names
$aliasMap = @{
    'read'       = @('Read')
    'edit'       = @('Write', 'Edit')
    'search'     = @('Grep', 'Glob')
    'todo'       = @('TodoWrite')
    'playwright/*' = @('mcp__playwright__*')
}

# Skills preloaded into each Claude subagent (Claude 'skills' field). Copilot loads skills on demand by name.
$skills = @{
    'datalinq-orchestrator'    = @('datalinq-connect', 'datalinq-pdf-report', 'datalinq-dashboard')
    'datalinq-data-analyst'    = @('datalinq-connect', 'datalinq-data')
    'datalinq-query-engineer'  = @('datalinq-connect', 'datalinq-query')
    'datalinq-designer'        = @('datalinq-from-image')
    'datalinq-view-coder'      = @('datalinq-view-edit', 'datalinq-pdf-author', 'datalinq-dashboard-author')
    'datalinq-visual-reviewer' = @('datalinq-view-review')
    'datalinq-code-reviewer'   = @('datalinq-view-review')
}

function Get-ListValue([string]$frontmatter, [string]$key) {
    $m = [regex]::Match($frontmatter, "(?m)^$key\s*:\s*\[(.*)\]\s*$")
    if (-not $m.Success) { return @() }
    return @([regex]::Matches($m.Groups[1].Value, "'([^']*)'|""([^""]*)""") | ForEach-Object {
        if ($_.Groups[1].Success) { $_.Groups[1].Value } else { $_.Groups[2].Value }
    })
}

function Get-ScalarValue([string]$frontmatter, [string]$key) {
    $m = [regex]::Match($frontmatter, "(?m)^$key\s*:\s*(.+?)\s*$")
    if ($m.Success) { return $m.Groups[1].Value } else { return $null }
}

New-Item -ItemType Directory -Force $dst | Out-Null

Get-ChildItem $src -Filter '*.agent.md' | ForEach-Object {
    $text = Get-Content -Raw -Encoding utf8 $_.FullName
    $m = [regex]::Match($text, '(?s)^---\r?\n(.*?)\r?\n---\r?\n(.*)$')
    if (-not $m.Success) { throw "No frontmatter in $($_.Name)" }
    $fm = $m.Groups[1].Value
    $body = $m.Groups[2].Value

    $name = Get-ScalarValue $fm 'name'
    $description = Get-ScalarValue $fm 'description'

    $tools = [System.Collections.Generic.List[string]]::new()
    $subagents = Get-ListValue $fm 'agents'
    if ($subagents.Count -gt 0) { $tools.Add("Agent($($subagents -join ', '))") }
    foreach ($t in (Get-ListValue $fm 'tools')) {
        if ($t -eq 'agent') { continue }
        if ($aliasMap.ContainsKey($t)) { $aliasMap[$t] | ForEach-Object { $tools.Add($_) }; continue }
        if ($t -match '^([^/]+)/(.+)$') { $tools.Add("mcp__$($Matches[1])__$($Matches[2])"); continue }
        Write-Warning "$($_.Name): no Claude mapping for tool '$t' (skipped)"
    }

    $out = [System.Text.StringBuilder]::new()
    [void]$out.AppendLine('---')
    [void]$out.AppendLine("name: $name")
    [void]$out.AppendLine("description: $description")
    [void]$out.AppendLine("tools: $(($tools | Select-Object -Unique) -join ', ')")
    if ($skills.ContainsKey($name)) { [void]$out.AppendLine("skills: [$($skills[$name] -join ', ')]") }
    [void]$out.AppendLine('---')
    [void]$out.AppendLine('<!-- Generated by agents/sync-claude-agents.ps1 from agents/copilot/' + $_.Name + ' - edit the Copilot file, then re-run the script. -->')
    [void]$out.Append($body)

    $target = Join-Path $dst ($name + '.md')
    [System.IO.File]::WriteAllText($target, $out.ToString().Replace("`r`n", "`n"), [System.Text.UTF8Encoding]::new($false))
    Write-Host "wrote $target"
}
